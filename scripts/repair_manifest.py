"""Rebuild a project_manifest.json from the files actually present in a workspace.

Why this exists: the manifest is the only artifact that is pure bookkeeping —
every other file in a workspace is pipeline output that can be regenerated by
re-running a step. If the manifest is lost or truncated, the workspace still has
its PDF and Revit export on disk but the backend cannot find them, and endpoints
start answering "No project PDF" for a project that plainly has one.

Every value written here is DERIVED from a file on disk (page count read from
the PDF, model title read from the export, timestamps from file mtimes). Nothing
is invented: keys that cannot be recovered are left out, and every reader treats
an absent key as a normal state.

    py -3.11 scripts/repair_manifest.py <slug> [--pdf-name "original.pdf"] [--apply]

Without --apply it prints the manifest it would write and changes nothing.
"""

from __future__ import annotations

import argparse
import json
import sys
from datetime import datetime, timezone
from pathlib import Path

REPO = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(REPO / "backend"))


def iso(ts: float) -> str:
    return datetime.fromtimestamp(ts, tz=timezone.utc).isoformat()


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("slug")
    ap.add_argument("--pdf-name", default=None,
                    help="Original upload filename; defaults to the stored name.")
    ap.add_argument("--uploaded-at", default=None,
                    help="True upload time (ISO-8601). Defaults to the stored value, "
                         "then to the PDF's mtime.")
    ap.add_argument("--ignore-existing", action="store_true",
                    help="Do not carry anything over from the current manifest. Use when "
                         "the current file is known to be corrupt.")
    ap.add_argument("--apply", action="store_true")
    args = ap.parse_args()

    workspace = REPO / "artifacts" / "projects" / args.slug
    if not workspace.is_dir():
        print(f"No workspace at {workspace}")
        return 1

    manifest_path = workspace / "project_manifest.json"
    existing: dict = {}
    if manifest_path.exists() and not args.ignore_existing:
        try:
            existing = json.loads(manifest_path.read_text(encoding="utf-8"))
        except json.JSONDecodeError:
            pass

    manifest: dict = {"project": args.slug}
    uploads = workspace / "uploads"

    pdf = uploads / "input.pdf"
    if pdf.is_file():
        import fitz

        manifest["pdf_path"] = str(pdf)
        with fitz.open(pdf) as doc:
            manifest["page_count"] = doc.page_count
        name = args.pdf_name or existing.get("pdf_original_name")
        if name:
            manifest["pdf_original_name"] = name

    revit = uploads / "input_revit.json"
    if revit.is_file():
        from app import export_watch, revit_v3_adapter

        raw = json.loads(revit.read_text(encoding="utf-8"))
        manifest["revit_path"] = str(revit)
        if existing.get("revit_original_name"):
            manifest["revit_original_name"] = existing["revit_original_name"]
        if revit_v3_adapter.is_v3(raw):
            manifest["revit_schema"] = "v3"
        title = export_watch.export_model_title(raw)
        if title:
            manifest["revit_model_title"] = title

    # Prefer a recorded upload time; fall back to the PDF's mtime, which is when
    # the file actually landed in the workspace.
    uploaded = args.uploaded_at or existing.get("uploaded_at")
    if not uploaded and pdf.is_file():
        uploaded = iso(pdf.stat().st_mtime)
    if uploaded:
        manifest["uploaded_at"] = uploaded
        manifest["created_at"] = existing.get("created_at") or uploaded
    manifest["updated_at"] = datetime.now(timezone.utc).isoformat()

    # Human-set metadata survives if it was there; never fabricated.
    for key in ("display_name", "client", "revision", "status", "notes"):
        if existing.get(key):
            manifest[key] = existing[key]

    rendered = json.dumps(manifest, indent=2)
    print(rendered)
    if not args.apply:
        print("\n(dry run — pass --apply to write)")
        return 0
    manifest_path.write_text(rendered, encoding="utf-8")
    print(f"\nwrote {manifest_path}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
